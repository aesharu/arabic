// Week number → { week, topics: [{ id, part: [i, n] }], grammar, review }
export const WEEKS = (() => {
  const out = [];
  let week = 3;
  for (const [topics, n, grammar] of SCHEDULE) {
    for (let i = 0; i < n; i++) {
      out.push({
        week: week++,
        topics: topics ? topics.map(id => ({ id, part: n > 1 ? [i, n] : null })) : [],
        grammar: Array.isArray(grammar) ? grammar[i] : grammar,
        review: !topics,
      });
    }
  }
  return out;
})();

