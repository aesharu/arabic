// What the voice reads (and what a recording is filed under): no emoji, no "هههه", no Latin words in quotes.
function speakable(ar) {
  return ar.replace(/[\p{Extended_Pictographic}\u{FE0F}]/gu, "").replace(/ه{3,}/g, "").replace(/[A-Za-z“”"]+/g, "").replace(/\s+/g, " ").replace(/^[\s،,]+/, "").trim();
}

