// As objects: { id, level, title, other, lines: [{ id, who, ar, say, en, uk }] }. Line ids ch.<chat>x<n> (✎, recordings).
export const CHATS = CHATS_RAW.map(c => ({
  ...c,
  lines: c.lines.map(([who, ar, say, en, uk], i) => ({ id: `ch.${c.id}x${i}`, chat: c.id, who, ar, say, en, uk, speak: speakable(ar), check: true })),
}));
export const CHAT_LINES = CHATS.flatMap(c => c.lines);
